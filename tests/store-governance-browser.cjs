      assert.match(await drawer.innerText(),/BG-MS-001/); await action('withdraw').click();
      assert.match(await drawer.innerText(),/已撤回/); await action('reedit').click();
      await drawer.locator('[name=reason]').fill('增加自由行范围'); await action('preview-submit').click();
