const { selectQueryView } = require('./finance-report-browser-support.cjs');
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { chromium } = require("playwright");

async function main() {
  const output = process.env.REPORT_QA_DIR || "/private/tmp/caesar-return-report-qa";
  const origin = process.env.REPORT_BASE_URL || "http://127.0.0.1:8000";
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const results = [], errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    page.on("pageerror", e => errors.push(e.message));
    const root = page.locator('.finance-report-page');
    const select = (key, value) => root.locator(`:scope > form [name="${key}"]`).selectOption(value);
    const submit = () => root.locator(':scope > form button[type="submit"]').click();
    const reset = async () => { await page.locator('[data-report-tab=actual]').click(); await root.locator('[data-reset]').click(); };
    const total = () => root.locator('[data-total]').innerText();
    const rows = () => root.locator('[data-table="main"] tbody tr').count();
    const show = async selector => { if (await root.locator(selector + ':visible').getAttribute('open') === null) await root.locator(selector + ':visible > summary').click(); };
    const close = async selector => { if (await root.locator(selector + ':visible').getAttribute('open') !== null) await root.locator(selector + ':visible > summary').click(); };
    const view = async key => { await selectQueryView(page, `${key}`); if (key !== 'financial') await submit(); };
    const download = async () => {
      const pending = page.waitForEvent("download");
      await root.locator('[data-export]:visible').click();
      const file = await pending, target = path.join(output, file.suggestedFilename());
      await file.saveAs(target);
      return fs.readFile(target, "utf8");
    };
    await page.goto(origin + "/merchant/data/return-report-details.html");
    await root.locator('[data-total]').waitFor();
    assert.match(await total(), /5\.60/);
    assert.equal(await rows(), 6);
    assert.equal(await root.locator('[data-table="main"] th').count(), 12);
    await page.screenshot({ path: path.join(output, "desktop-actual.png") });
    await show('.report-columns');
    assert.equal(await root.locator('.report-order-column-groups fieldset').count(), 5);
    for (const key of ["order", "product"]) assert.equal(await root.locator(`[data-column="${key}"]`).isDisabled(), true);
    for (const key of ["record", "completionType", "completionBasis", "confirmedBy", "confirmedAt", "allocationBasis", "salesLeader", "productCompany", "contractCompany", "managementZone", "incomeMethod", "taxTreatment"]) await root.locator(`[data-column="${key}"]`).check();
    let csv = await download();
    assert.match(csv, /"完成依据"/);
    assert.match(csv, /演示会务第一阶段验收记录/);
    assert.match(csv, /2026-05-07 21:00/);
    assert.match(csv, /C公司（演示）/);
    await page.screenshot({ path: path.join(output, "desktop-fields.png") });
    results.push("actual: 12 default columns, grouped optional completion and ownership facts, 56,000 retained");

    await show('details.report-more');
    await select('salesLeader', '赵主管（演示）');
    await select('company', 'B');
    assert.equal(await root.locator('[name="salesLeader"]').inputValue(), '');
    await select('company', 'A');
    await select('productCompany', 'B');
    await submit();
    assert.match(await total(), /1\.00/);
    assert.equal(await rows(), 1);
    await reset();
    await select('unit', 'yuan');
    await submit();
    await root.locator('[data-page-size]').selectOption('5');
    assert.equal(await rows(), 5);
    await select('salesDepartment', '门店销售部（演示）');
    await root.locator('[data-sort="amount"]').click();
    await root.locator('[data-page="1"]').click();
    csv = await download();
    assert.match(csv, /56,000\.00/);
    assert.match(csv, /"销售部门","全部"/);
    assert.equal((csv.match(/^"O\d+"/gm) || []).length, 6);
    await submit();
    assert.match(await total(), /17,000\.00/);
    assert.equal(await rows(), 3);
    results.push("independent responsibility filters; pending conditions do not affect pagination, sorting or full export");

    await reset();
    await view('financial');
    const finance = root.locator('[data-return-finance]');
    assert.equal(await finance.locator('[aria-label="财务确认主表"] th').count(), 12);
    assert.match(await finance.locator('h2').innerText(), /完成业务核对/);
    assert.match(await finance.locator('[data-rf-total]').innerText(), /6 条已完成记录/);
    assert.match(await finance.locator('tbody').first().innerText(), /未提供记录/);
    await show('.report-columns');
    for (const key of ['incomePeriod', 'costPeriod', 'incomeRecord', 'costRecord']) await finance.locator(`[data-rf-column="${key}"]`).check();
    csv = await download();
    assert.match(csv, /"收入会计期间"/);
    assert.match(csv, /"成本会计期间"/);
    assert.match(csv, /实际完成日期/);
    assert.equal((csv.match(/^"O\d+"/gm) || []).length, 6);
    assert.ok(!csv.includes('"财务确认期间"'));
    assert.ok(!csv.includes('"计划完成开始日'));
    await close('.report-columns');
    await finance.locator('[aria-label="财务确认主表"]').evaluate(e => { e.scrollLeft = e.scrollWidth; });
    await finance.locator('[data-rf-results]').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'desktop-financial.png') });
    results.push("financial: separate settlement/income/cost, actual-date scope, missing records not zero, independent periods exported");

    await view('future');
    assert.match(await total(), /1\.80/);
    await show('.report-columns');
    for (const key of ['actual', 'managementMonth', 'incomeStatus', 'incomeMethod', 'taxTreatment']) assert.equal(await root.locator(`[data-column="${key}"]`).count(), 0);
    await root.locator('[data-column="planBasis"]').check();
    csv = await download();
    assert.match(csv, /演示会务第二阶段安排/);
    assert.ok(!csv.includes('"收入确认资料"'));
    assert.ok(!csv.includes('"结算状态"'));
    assert.ok(!csv.includes('"已查询范围开始日"'));
    assert.match(csv, /"计划完成年份"/);
    await select('finishYear', '2027');
    await submit();
    assert.equal(await rows(), 1);
    assert.match(await total(), /0\.90/);
    await select('finishYear', '');
    await root.locator('[name="planStart"]').fill('2026-05-01');
    await root.locator('[name="planEnd"]').fill('2026-05-07');
    await submit();
    assert.equal(await rows(), 0);
    results.push("future: 18,000, next-year 9,000; only plan dates/basis, no completion or financial fields");

    await reset();
    await root.locator(':scope > form [name="start"]').fill('2026-05-07');
    await root.locator(':scope > form [name="end"]').fill('2026-05-01');
    await submit();
    assert.equal(await root.locator('[data-error]').isVisible(), true);
    assert.match(await total(), /5\.60/);
    await select('calendar', 'management');
    await submit();
    assert.equal(await root.locator('[data-error]').isVisible(), false);
    assert.match(await total(), /5\.60/);
    csv = await download();
    assert.match(csv, /演示管理月 2026-05/);
    assert.ok(!csv.includes('"已查询范围开始日"'));
    assert.ok(!csv.includes('"统计期间"'));
    await reset();
    await view('adjustments');
    assert.equal(await rows(), 0);
    assert.match(await total(), /未提供完成后调整记录/);
    await show('.report-columns');
    for (const key of ['originalSettlement', 'adjustmentStatus', 'originalFinancePeriod']) await root.locator(`[data-column="${key}"]`).check();
    csv = await download();
    assert.match(csv, /"本次会计期间"/);
    assert.match(csv, /"原会计期间"/);
    assert.ok(!csv.includes('"实际完成年份"'));
    results.push("management month excludes inactive dates; invalid dates preserve results; adjustments retain original/current period without fake records");

    await reset();
    assert.equal(await root.locator('[data-table="main"] tbody a, [data-table="main"] tbody button').count(), 0);
    const url = page.url();
    await root.locator('[data-table="main"] tbody td').first().click();
    assert.equal(page.url(), url);
    assert.equal(await root.locator('[role="dialog"]').count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    await show('.report-columns');
    const keys = await root.locator('[data-column]:not(:disabled)').evaluateAll(es => es.map(e => e.dataset.column));
    for (const key of keys) await root.locator(`[data-column="${key}"]`).check();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    assert.equal(await root.locator('.report-order-column-groups:visible').evaluate(e => e.scrollWidth > e.clientWidth + 1), false);
    await page.getByRole('button', { name: '收起或展开侧栏' }).click();
    await page.waitForFunction(() => document.querySelector('.finance-report-page').clientWidth > 280);
    await page.locator('.content').evaluate(e => { e.scrollTop = 0; });
    await page.screenshot({ path: path.join(output, 'mobile-default.png') });
    await root.locator('.report-order-column-groups fieldset').first().scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'mobile-fields.png') });
    await root.locator('.report-columns:visible > summary').click();
    await root.locator('[data-results] .report-table-scroll').evaluate(e => { e.scrollLeft = e.scrollWidth; });
    await root.locator('[data-results] .report-section').screenshot({ path: path.join(output, 'mobile-table.png') });
    for (const key of ['financial', 'future', 'adjustments']) {
      await view(key);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
      await close('.report-columns');
      const current = key === 'financial' ? finance.locator('[data-rf-results]') : root.locator('[data-results] .report-section');
      await current.locator('.report-table-scroll').first().evaluate(e => { e.scrollLeft = e.scrollWidth; });
      await current.screenshot({ path: path.join(output, 'mobile-' + key + '.png') });
    }
    results.push("no drilldowns; all optional fields, table horizontal scroll and all four views fit narrow viewport");

    await page.setViewportSize({ width: 1440, height: 1000 });
    for (const file of ['performance-reports.html', 'product-reports.html', 'order-report-details.html']) {
      await page.goto(origin + '/merchant/data/' + file);
      await root.locator('[data-total]').first().waitFor();
      assert.equal(await root.locator('[name="incomeStatus"]').count(), 0);
      assert.ok((await download()).includes('演示数据，非财务实绩'));
      await page.setViewportSize({ width: 390, height: 844 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
      await page.setViewportSize({ width: 1440, height: 1000 });
    }
    assert.deepEqual(errors, []);
    results.push("other three reports load/export on desktop and mobile; zero script errors");
    await fs.writeFile(path.join(output, 'results.json'), JSON.stringify({ results, errors }, null, 2));
    console.log(JSON.stringify({ output, results, errors }, null, 2));
  } finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
