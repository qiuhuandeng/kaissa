const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require('playwright');

async function main() {
  const origin = process.env.REPORT_BASE_URL || 'http://127.0.0.1:8002';
  const output = process.env.REPORT_QA_DIR || '/private/tmp/caesar-budget-target-qa';
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [], results = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    page.on('pageerror', e => errors.push(e.message));
    const root = page.locator('[data-budget-targets]');
    const row = id => root.locator(`[data-row="${id}"]`);
    const edit = key => root.locator(`[data-edit-form] [name="${key}"]`);
    const filter = key => root.locator(`[data-filter] [name="${key}"]`);
    const submit = () => root.locator('[data-filter] button[type="submit"]').click();
    const back = () => root.locator('[data-back]').click();
    const download = async () => {
      const pending = page.waitForEvent('download'); await root.locator('[data-export]').click();
      const file = await pending, target = path.join(output, file.suggestedFilename());
      await file.saveAs(target); return fs.readFile(target, 'utf8');
    };
    await page.goto(origin + '/merchant/data/budget-targets.html');
    await root.locator('[data-total]').waitFor();
    assert.match(await root.locator('[data-total]').innerText(), /6 个任务版本/);
    assert.equal(await root.locator('th.bt-action').evaluate(e => e.getBoundingClientRect().width), 176);
    assert.equal(await root.locator('th.bt-action').evaluate(e => getComputedStyle(e).position), 'sticky');
    await page.screenshot({ path: path.join(output, 'desktop-list.png') });
    await filter('metric').selectOption('margin');
    await root.locator('[data-sort="annual"]').click();
    let csv = await download(); assert.match(csv, /"任务指标","全部"/); assert.match(csv, /直营区域旧任务/);
    assert.match(csv, /"12月"/); assert.match(csv, /下级年度分配/);
    await submit(); assert.match(await root.locator('[data-total]').innerText(), /1 个任务版本/);
    csv = await download(); assert.match(csv, /产品经营组毛利任务/); assert.doesNotMatch(csv, /集团订单年度任务/);
    await filter('year').fill('2027'); await submit(); assert.match(await root.locator('[data-result]').innerText(), /当前条件无任务/);
    await root.locator('[data-reset]').click();
    results.push('列表固定操作列、查询与待查询隔离、分页全量月度及下级分配导出、空态');

    await row('T2').getByRole('button', { name: '提交', exact: true }).click();
    assert.match(await root.locator('[data-error]').innerText(), /齐全/);
    await row('T2').getByRole('button', { name: '编辑', exact: true }).click();
    assert.equal(await edit('scope').isDisabled(), true);
    await edit('basis').fill('测试依据');
    await root.locator('[data-save]').click();
    await row('T2').getByRole('button', { name: '提交', exact: true }).click();
    assert.match(await root.locator('[data-error]').innerText(), /12个月/);
    await row('T2').getByRole('button', { name: '编辑', exact: true }).click();
    for (let i = 0; i < 12; i++) await edit('month' + i).fill('10000');
    assert.match(await root.locator('[data-month-total]').innerText(), /差额 0.00 · 0个月未填写/);
    await root.locator('[data-save]').click();
    await row('T2').getByRole('button', { name: '提交', exact: true }).click();
    assert.match(await row('T2').innerText(), /审批中/);
    assert.equal(await row('T2').getByRole('button', { name: '编辑', exact: true }).count(), 0);
    await row('T2').getByRole('button', { name: '查看', exact: true }).click();
    assert.equal(await edit('annual').isDisabled(), true);
    assert.match(await root.locator('.bt-history').innerText(), /未提供正式批准记录.*提交审批/s);
    await back(); await row('T2').getByRole('button', { name: '撤回', exact: true }).click();
    page.once('dialog', d => d.accept()); await row('T2').getByRole('button', { name: '作废', exact: true }).click();
    assert.match(await row('T2').innerText(), /已作废/);
    results.push('金额及依据校验、草稿提交审批中、只读查看、撤回作废、记录留痕且不批准');

    await row('T1').getByRole('button', { name: '新建调整' }).click();
    assert.equal(await edit('start').inputValue(), ''); assert.equal(await edit('metric').isDisabled(), true);
    await edit('start').fill('2026-07-01'); await edit('basis').fill('测试调整依据'); await edit('reason').fill('年度任务增加');
    await edit('annual').fill('850000'); await edit('month11').fill('80000');
    assert.match(await root.locator('[data-version-comparison]').innerText(), /840,000.00.*850,000.00.*10,000.00/);
    await root.locator('[data-child-amount]').first().fill('900000');
    await root.locator('[data-save]').click(); assert.match(await root.locator('[data-edit-error]').innerText(), /超出/);
    await root.locator('[data-child-amount]').first().fill('500000');
    await root.locator('[data-add-child]').click();
    await root.locator('[data-child-scope]').last().selectOption('store');
    await root.locator('[data-child-amount]').last().fill('1');
    await root.locator('[data-save]').click(); assert.match(await root.locator('[data-edit-error]').innerText(), /交叉/);
    await root.locator('[data-remove="2"]').click();
    await root.locator('[data-editor]').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'desktop-adjustment.png') });
    await root.locator('[data-save]').click();
    assert.match(await row('T1').innerText(), /840,000.00/);
    await row('T1').getByRole('button', { name: '新建调整' }).click(); assert.match(await root.locator('[data-error]').innerText(), /已有/);
    await filter('date').fill('2026-08-01'); await filter('level').selectOption('集团'); await submit();
    assert.match(await root.locator('[data-total]').innerText(), /2 个任务版本/);
    assert.match(await row('T7').innerText(), /850,000.00/);
    csv = await download(); assert.match(csv, /年度任务增加/); assert.match(csv, /"V2","草稿"/);
    results.push('调整保留原版、年度前后对照、下级超额及跨层重复校验、未批准版本独立查询');

    await root.locator('[data-new]').click();
    await edit('name').fill('=演示新任务'); await edit('scope').selectOption('product-a');
    assert.match(await root.locator('[data-scope-facts]').innerText(), /产品责任/);
    await edit('metric').selectOption('margin');
    assert.equal(await edit('definition').locator('option').count(), 3);
    await edit('year').fill('2027'); await edit('start').fill('2027-01-01'); await edit('end').fill('2027-12-31');
    await root.locator('[data-save]').click();
    await root.locator('[data-reset]').click(); await filter('search').fill('=演示新任务'); await submit();
    csv = await download(); assert.match(csv, /"'=演示新任务"/);
    await row('T8').getByRole('button', { name: '编辑', exact: true }).click(); await edit('reason').fill('未保存');
    page.once('dialog', d => d.dismiss()); await back(); assert.equal(await root.locator('[data-editor]').isVisible(), true);
    page.once('dialog', d => d.accept()); await back();
    results.push('新建产品责任毛利任务、年度范围、缺数草稿、导出公式防护、未保存退出确认');

    await root.locator('[data-reset]').click(); await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '收起或展开侧栏' }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await root.locator('.report-table-scroll').evaluate(e => { e.scrollLeft = e.scrollWidth; });
    await root.locator('[data-result]').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'mobile-list.png') });
    assert.equal(await root.locator('td.bt-action').first().evaluate(e => e.getBoundingClientRect().width), 120);
    await row('T1').getByRole('button', { name: '查看', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'mobile-editor.png') });
    await root.locator('.bt-months').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'mobile-months.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const widths = await root.locator('.bt-months input').evaluateAll(es => es.map(e => e.getBoundingClientRect().width));
    assert.ok(widths.every(w => w > 100));
    results.push('390px表格内部横滚、操作列可达、月度输入稳定、编辑页不溢出');

    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(origin + '/merchant/data/order-report-details.html'); await page.locator('[data-total]').waitFor();
    await page.locator('a[href$="data/budget-targets.html"]').first().click(); await root.locator('[data-total]').waitFor();
    assert.match(await root.locator('[data-total]').innerText(), /6 个任务版本/);
    assert.match(await row('T2').innerText(), /草稿/);
    assert.deepEqual(errors, []);
    results.push('经营报表到预算导航局部切页、刷新恢复示例、不串页、浏览器错误为0');
    await fs.writeFile(path.join(output, 'results.json'), JSON.stringify({ results, errors }, null, 2));
    console.log(JSON.stringify({ passed: results.length, results, output }, null, 2));
  } finally { await browser.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
