const { selectQueryView } = require('./finance-report-browser-support.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require('playwright');

async function main() {
  const output = process.env.REPORT_QA_DIR || '/private/tmp/caesar-report-management-qa';
  const origin = process.env.REPORT_BASE_URL || 'http://127.0.0.1:8000';
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [], results = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    page.on('pageerror', e => errors.push(e.message));
    const root = page.locator('[data-report-management]');
    const tab = key => page.locator(`[data-report-tab="${key}"]`).click();
    const filter = key => root.locator(`[data-filter] [name="${key}"]`);
    const edit = key => root.locator(`[data-edit-form] [name="${key}"]`);
    const submit = () => root.locator('[data-filter] button[type="submit"]').click();
    const row = id => root.locator(`tr:has([data-id="${id}"])`);
    const total = () => root.locator('[data-total]').innerText();
    const download = async () => {
      const pending = page.waitForEvent('download');
      await root.locator('[data-export]').click();
      const file = await pending, target = path.join(output, file.suggestedFilename());
      await file.saveAs(target); return fs.readFile(target, 'utf8');
    };
    await page.goto(origin + '/merchant/data/report-management.html');
    await root.locator('[data-total]').waitFor();
    assert.match(await total(), /16 项缺口.*6 条业务.*54,000.00/);
    await page.screenshot({ path: path.join(output, 'desktop-checks.png') });
    await filter('company').selectOption('B');
    await root.locator('[data-sort="amount"]').click();
    await root.locator('[data-page="1"]').click();
    let csv = await download();
    assert.match(csv, /"销售公司","演示集团全部"/);
    assert.equal((csv.match(/^"O\d+"/gm) || []).length, 16);
    await submit(); assert.match(await total(), /19,000.00/);
    await filter('basis').selectOption('returns'); await filter('company').selectOption('');
    await filter('issue').selectOption('cost'); await submit();
    assert.match(await total(), /6 项缺口.*56,000.00/);
    csv = await download(); assert.match(csv, /未提供确认记录/); assert.match(csv, /完成记录号/);
    await filter('issue').selectOption('salesLeader'); await submit();
    assert.match(await total(), /0 项缺口/);
    assert.match(await root.locator('[data-result]').innerText(), /当前条件无缺口记录/);
    await filter('end').fill('2026-05-08'); await submit();
    assert.match(await root.locator('[data-error]').innerText(), /截止日/);
    results.push('数据核对、去重金额、筛选草稿隔离、分页全量导出、财务缺数、空态及截止校验');

    await tab('rules');
    await row('RULE-4').getByRole('button', { name: '提交', exact: true }).click();
    assert.match(await root.locator('[data-error]').innerText(), /不能提交/);
    await row('RULE-4').getByRole('button', { name: '编辑', exact: true }).click();
    assert.equal(await edit('sourceId').isDisabled(), true);
    await edit('target').selectOption('呼叫中心B区（拟）');
    await edit('basis').fill('预算负责人提供的演示依据');
    await root.locator('[data-save]').click();
    await row('RULE-4').getByRole('button', { name: '提交', exact: true }).click();
    assert.match(await row('RULE-4').innerText(), /待确认/);
    assert.equal(await row('RULE-4').getByRole('button', { name: '编辑', exact: true }).count(), 0);
    await row('RULE-4').getByRole('button', { name: '查看', exact: true }).click();
    assert.equal(await edit('target').isDisabled(), true);
    assert.match(await root.locator('.rm-record-history').innerText(), /提交待确认/);
    await root.locator('[data-back]').click();
    await row('RULE-4').getByRole('button', { name: '撤回', exact: true }).click();
    page.once('dialog', d => d.accept());
    await row('RULE-4').getByRole('button', { name: '作废', exact: true }).click();
    assert.match(await row('RULE-4').innerText(), /已作废/);
    results.push('草稿编辑、提交必填校验、待确认只读、撤回和作废，操作由主状态决定');

    await row('RULE-2').getByRole('button', { name: '新建变更' }).click();
    assert.equal(await edit('start').inputValue(), '2027-01-01');
    await edit('end').fill('2027-12-31'); await edit('reason').fill('演示下一年分区调整');
    await edit('basis').fill('待财务确认的演示依据');
    await edit('target').selectOption('出境经营区（演示）');
    await edit('start').fill('2026-12-31'); await root.locator('[data-save]').click();
    assert.match(await root.locator('[data-edit-error]').innerText(), /交叠/);
    await edit('start').fill('2027-01-01');
    await page.screenshot({ path: path.join(output, 'desktop-version.png') });
    await root.locator('[data-save]').click();
    assert.match(await row('RULE-2').innerText(), /欧洲经营区（演示）/);
    await filter('date').fill('2027-06-01'); await submit();
    assert.match(await total(), /1 条对应记录/);
    assert.match(await root.locator('.rm-with-actions tbody').innerText(), /草稿.*出境经营区（演示）.*2027-01-01.*V2/s);
    await root.locator('[data-new]').click(); await edit('reason').fill('未保存内容');
    page.once('dialog', d => d.dismiss()); await root.locator('[data-back]').click();
    assert.equal(await root.locator('[data-editor]').isVisible(), true);
    page.once('dialog', d => d.accept()); await root.locator('[data-back]').click();
    results.push('生效期间重叠校验、新版本保留历史、适用日期筛选、未保存离开确认');

    await tab('organizations');
    await row('RULE-9').getByRole('button', { name: '编辑', exact: true }).click();
    assert.equal(await edit('target').locator('option').count(), 1);
    assert.match(await root.locator('[data-source-facts]').innerText(), /核算部门.*未提供对应资料/s);
    await root.locator('[data-back]').click();
    await page.screenshot({ path: path.join(output, 'desktop-organizations.png') });
    const width = await root.locator('th.rm-action-col').evaluate(e => e.getBoundingClientRect().width);
    assert.equal(width, 176);
    const pos = await root.locator('th.rm-action-col').evaluate(e => getComputedStyle(e).position);
    assert.equal(pos, 'sticky');
    results.push('组织对应独立维护，核算部门不推填，桌面固定操作列176px');

    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '收起或展开侧栏' }).click();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    assert.equal(overflow, false);
    await root.locator('.report-table-scroll').evaluate(e => { e.scrollLeft = e.scrollWidth; });
    await root.locator('.report-section').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'mobile-organizations.png') });
    assert.equal(await root.locator('td.rm-action-col').first().evaluate(e => e.getBoundingClientRect().width), 176);
    await row('RULE-9').getByRole('button', { name: '编辑', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'mobile-editor.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    results.push('390px窄屏表格内部滚动、固定操作列和编辑页不撑破外壳');

    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(origin + '/merchant/data/order-report-details.html');
    await page.locator('[data-total]').waitFor();
    const nav = page.locator('a[href$="data/report-management.html"]');
    await nav.first().click();
    await root.locator('[data-total]').waitFor();
    assert.equal(await page.locator('[data-report-tab=organizations]').getAttribute('aria-selected'), 'true');
    await tab('rules'); await root.locator('[data-reset]').click(); assert.match(await row('RULE-4').innerText(), /草稿/);
    assert.equal(await root.locator('[data-report-page]').count(), 0);
    assert.deepEqual(errors, []);
    results.push('现有报表到新导航的局部切页可加载，不串页；重新进入恢复演示资料，无浏览器异常');
    await fs.writeFile(path.join(output, 'results.json'), JSON.stringify({ results, errors }, null, 2));
    console.log(JSON.stringify({ passed: results.length, results, output }, null, 2));
  } finally { await browser.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
