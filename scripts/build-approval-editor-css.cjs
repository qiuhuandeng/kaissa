/* Run with rrweb-cssom available on NODE_PATH. Generated CSS stays committed for static hosting. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),CSS=require('rrweb-cssom');
const root=path.resolve(__dirname,'..'),read=f=>fs.readFileSync(path.join(root,f),'utf8');
const sources=['shared/nav-admin.js','shared/approval-config.js','admin/approval-template-edit.html'];
const styles=['shared/org-admin-members.css','shared/approval-config.css','shared/style.css'];
const words=new Set(sources.map(read).join('\n').match(/[A-Za-z_][\w-]*/g));
// Conservative: retain the WHOLE rule if ANY class could occur in the editor or shell.
// Keep classless selectors, all declarations, pseudo states, media/supports and keyframes.
function filter(rules){return [...rules].map(rule=>{
 if(rule.type===3)return ''; // Imports are explicitly included above; other modules are not needed.
 if(rule.selectorText){const names=[...rule.selectorText.matchAll(/\.([a-zA-Z_][\w-]*)/g)].map(m=>m[1]);if(names.length&&!names.some(n=>words.has(n)||n.startsWith('ac-')||n.startsWith('nav-')))return '';return rule.cssText;}
 if(rule.cssRules&&[4,12].includes(rule.type)){const body=filter(rule.cssRules);return body?rule.cssText.slice(0,rule.cssText.indexOf('{')+1)+'\n'+body+'\n}':'';}
 return rule.cssText;
}).filter(Boolean).join('\n');}
const hash=crypto.createHash('sha256').update([...sources,...styles].map(read).join('\n')).digest('hex');
const output='/* Generated by scripts/build-approval-editor-css.cjs; do not edit.\n * Source SHA256: '+hash+' */\n'+styles.slice(0,2).map(read).join('\n')+'\n'+filter(CSS.parse(read(styles[2])).cssRules)+'\n';
const target=path.join(root,'shared/approval-editor-page.css');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('Approval editor CSS is stale; regenerate it.');process.exit(1);}}
else fs.writeFileSync(target,output);
console.log('Approval editor CSS: '+Buffer.byteLength(output)+' bytes');
