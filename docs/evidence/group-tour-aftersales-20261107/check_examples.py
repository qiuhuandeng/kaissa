D = lambda x: Decimal(str(x))
checks = []


def serial(value):
    if isinstance(value, (list, tuple)):
        return [serial(x) for x in value]
    if isinstance(value, bool):
        return value
    return format(D(value), '.2f')


def check(case, name, actual, expected):
    ok = serial(actual) == serial(expected)
    checks.append(dict(case=case, name=name, actual=serial(actual), expected=serial(expected), passed=ok))
    if not ok:
        raise AssertionError((case, name, actual, expected))


def customer(collected, effective, refunded=0):
    balance = D(collected) - D(refunded) - D(effective)
    return [max(-balance, D(0)), max(balance, D(0))]


def supplier(cost, paid, returned=0):
    balance = D(cost) - D(paid) + D(returned)
    return [max(balance, D(0)), max(-balance, D(0))]


