def d(x):
    return Decimal(str(x))


def money(x, places=2):
    return d(x).quantize(d(1).scaleb(-places), rounding=ROUND_HALF_UP)


def serial(x):
    if isinstance(x, (list, tuple)):
        return [serial(v) for v in x]
    return format(x, 'f') if isinstance(x, Decimal) else x


checks, stages = [], []


def check(case, name, actual, expected):
    ok = actual == expected
    checks.append(dict(case=case, name=name, actual=serial(actual), expected=serial(expected), passed=ok))
    if not ok:
        raise AssertionError((case, name, actual, expected))


