def d(value):
    return Decimal(str(value))


def money(value):
    return d(value).quantize(d('0.01'), rounding=ROUND_HALF_UP)


def serial(value):
    if isinstance(value, (list, tuple)):
        return [serial(v) for v in value]
    return format(value, 'f') if isinstance(value, Decimal) else value


checks, stages = [], []


def check(case, name, actual, expected):
    passed = actual == expected
    checks.append(dict(case=case, name=name, actual=serial(actual), expected=serial(expected), passed=passed))
    if not passed:
        raise AssertionError((case, name, actual, expected))


